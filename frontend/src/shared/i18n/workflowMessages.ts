// Historical snapshots keep their original string fields. Translate only known system
// messages at presentation time; arbitrary user values and artifact prose never enter here.
export function workflowNotice(source: string, t: Translate): string {
  const groups = /^有效分组超过 (\d+) 个，请选择分类字段，避免使用样本编号作为分组。$/.exec(source)
  if (groups) return t('有效分组超过 {count} 个，请选择分类字段，避免使用样本编号作为分组。', { count: groups[1] })
  const cells = /^数值列必须包含实际数值，且非缺失值全部为数值；文本数字、布尔、日期、公式或错误不能直接分析，例如 ([A-Z]+\d+(?:、[A-Z]+\d+)*)。$/.exec(source)
  if (cells) return t('数值列必须包含实际数值，且非缺失值全部为数值；文本数字、布尔、日期、公式或错误不能直接分析，例如 {cells}。', { cells: cells[1] })
  const metric = /^(均值|样本标准差|最小值|Q1|中位数|Q3|最大值|四分位距)超出可表示的数值范围，结果标记为无法计算。$/.exec(source)
  if (metric) return t('{metric}超出可表示的数值范围，结果标记为无法计算。', { metric: t(metric[1]) })
  return legacyNotices.has(source) ? t(source) : source
}
