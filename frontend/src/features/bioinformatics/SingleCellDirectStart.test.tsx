import {afterEach,expect,it,vi} from 'vitest'
import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {apiFetch} from '../../shared/api/client'
import SingleCellDirectStart from './SingleCellDirectStart'
import {capabilitiesFixture,rawFixture} from './spatialFixtures'
vi.mock('../../shared/api/client',()=>({apiFetch:vi.fn(),getApiUserId:()=> 'owner1',onApiSessionChanged:()=>()=>{}}))
afterEach(()=>{cleanup();vi.clearAllMocks();sessionStorage.clear()})
it('opens a repeat with the exact saved parameters and design without starting computation',async()=>{
 const params={...capabilitiesFixture.default_params,seed:17,hvg_count:1234}
 vi.mocked(apiFetch).mockImplementation(async(_url,init)=>Response.json(init?.method==='POST'?{id:'repeat',task:{id:'task'}}:capabilitiesFixture))
 render(<SingleCellDirectStart projectId="p1" source={rawFixture} onNavigate={()=>{}} initialParams={params} observationMapVersionId="mapping" designVersionId="design"/> )
 expect(await screen.findByLabelText('随机 seed')).toHaveProperty('value','17')
 expect(screen.getByLabelText('HVG 数量')).toHaveProperty('value','1234')
 expect(vi.mocked(apiFetch).mock.calls.filter(c=>c[1]?.method==='POST')).toHaveLength(0)
 fireEvent.click(screen.getByRole('button',{name:'开始单细胞分析'}))
 await waitFor(()=>expect(vi.mocked(apiFetch).mock.calls.filter(c=>c[1]?.method==='POST')).toHaveLength(1))
 const sent=JSON.parse(String(vi.mocked(apiFetch).mock.calls.find(c=>c[1]?.method==='POST')![1]?.body))
 expect(sent).toMatchObject({observation_map_version_id:'mapping',design_version_id:'design',params:{seed:17,hvg_count:1234}})
})
it('submits library QC and optional real-tool settings in the same analysis request',async()=>{
 const navigate=vi.fn()
 const capabilities={...capabilitiesFixture,single_cell_libraries:[{library_id:'libA',sample_id:'sampleA'},{library_id:'libB',sample_id:'sampleB'}]}
 vi.mocked(apiFetch).mockImplementation(async(_url,init)=>Response.json(init?.method==='POST'?{id:'run2',task:{id:'task2'}}:capabilities))
 render(<SingleCellDirectStart projectId="p1" source={rawFixture} onNavigate={navigate}/>)
 const enable=await screen.findByLabelText('运行 scDblFinder 双细胞检测')
 expect((enable as HTMLInputElement).checked).toBe(false)
 fireEvent.click(enable)
 fireEvent.click(screen.getByLabelText('排除预测双细胞'))
 fireEvent.change(screen.getByLabelText('预期双细胞比例（留空使用工具估计）'),{target:{value:'0.04'}})
 fireEvent.click(screen.getByLabelText('运行 decontX 环境 RNA 校正'))
 fireEvent.change(screen.getByLabelText('libA 最低 counts'),{target:{value:'500'}})
 fireEvent.change(screen.getByLabelText('libB 最低检测基因数'),{target:{value:'200'}})
 fireEvent.click(screen.getByRole('button',{name:'开始单细胞分析'}))
 await waitFor(()=>expect(navigate).toHaveBeenCalledWith({view:'bio-analysis',fileId:'',runId:'run2'}))
 const posts=vi.mocked(apiFetch).mock.calls.filter(c=>c[1]?.method==='POST')
 expect(posts).toHaveLength(1)
 const sent=JSON.parse(String(posts[0][1]?.body))
 expect(sent.params.doublet).toEqual({enabled:true,exclude_predicted:true,expected_rate:0.04})
 expect(sent.params.decontx).toEqual({enabled:true})
 expect(sent.params.library_qc_overrides).toEqual([{library_id:'libA',min_counts:500},{library_id:'libB',min_genes:200}])
})

