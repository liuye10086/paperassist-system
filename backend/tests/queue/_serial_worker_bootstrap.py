"""Acceptance-only observer: retain the real executor and real DOCX builder."""
import json
import os
from pathlib import Path
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from app.workers.config import configure_execution_environment

configure_execution_environment()


def observe(kind, **values):
    record = dict(kind=kind, pid=os.getpid(), worker=os.environ['SERIAL_PROBE_WORKER'],
                  time_ns=time.time_ns(), monotonic_ns=time.monotonic_ns(), **values)
    descriptor = os.open(os.environ['SERIAL_PROBE_EVENTS'], os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
    try:
        os.write(descriptor, (json.dumps(record, sort_keys=True) + '\n').encode())
    finally:
        os.close(descriptor)


if __name__ == '__main__':
    from celery.signals import task_postrun, task_prerun, worker_ready
    from app.domain.tasks import execution
    from app.workers.celery_app import get_app

    original_builder = execution.build_report

    def observed_builder(*args, **kwargs):
        # The pause makes competing delivery observable; generated bytes still
        # come from the production Word builder using frozen synthetic sources.
        observe('word_build_start')
        time.sleep(1)
        content = original_builder(*args, **kwargs)
        observe('word_build_finished', bytes=len(content))
        return content

    execution.build_report = observed_builder

    @worker_ready.connect(weak=False)
    def ready(**kwargs):
        observe('ready')

    @task_prerun.connect(weak=False)
    def starting(task_id=None, args=None, **kwargs):
        observe('delivery_start', message_id=task_id, task_id=args[0] if args else None)

    @task_postrun.connect(weak=False)
    def finished(task_id=None, args=None, state=None, **kwargs):
        observe('delivery_finished', message_id=task_id,
                task_id=args[0] if args else None, celery_state=state)

    get_app().worker_main([
        'worker', '--loglevel=WARNING', '--pool=prefork', '--concurrency=1',
        '--max-tasks-per-child=1', '--without-gossip', '--without-mingle',
        '--without-heartbeat', '--hostname=' + os.environ['SERIAL_PROBE_WORKER'],
    ])
